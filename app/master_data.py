def _build(rows: list[tuple], skip: set[str]) -> list[dict]:
    result = []
    for i, (code, name, kana, grp, tax, role) in enumerate(rows):
        if code in skip:
            continue
        result.append({
            "code": code, "name": name, "kana": kana,
            "category": GROUP_MAP[grp], "grp": grp,
            "default_tax_class": tax, "role": role, "sort_order": i * 10,
        })
    return result


def standard_accounts_for(entity_type: str) -> list[dict]:
    """汎用 (3 桁) 科目表。"""
    skip = set()
    for code, _n, _k, _g, _t, role in STANDARD_ACCOUNTS:
        if entity_type == "sole" and (role == "retained" or code in ("400", "401", "410", "411")):
            skip.add(code)
        if entity_type == "corp" and role in ("owner_capital", "owner_drawing", "owner_contrib"):
            skip.add(code)
    return _build(STANDARD_ACCOUNTS, skip)


def tkc_accounts_for(entity_type: str) -> list[dict]:
    """TKC コード体系の科目表。"""
    skip = TKC_SOLE_ONLY if entity_type == "corp" else TKC_CORP_ONLY
    return _build(TKC_ACCOUNTS, set(skip))


def chart_accounts(chart: str, entity_type: str) -> list[dict]:
    if chart == "none":
        return []
    if chart == "standard":
        return standard_accounts_for(entity_type)
    return tkc_accounts_for(entity_type)


def provisional_codes(chart: str = "tkc") -> list[str]:
    """コードが未確認で暫定コードを充てている科目のコード一覧。"""
    return [c for c, *_ in TKC_ACCOUNTS if c.startswith(PROVISIONAL_PREFIX)]
