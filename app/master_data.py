def standard_accounts_for(entity_type: str) -> list[dict]:
    """事業形態に応じた標準科目リストを返す。"""
    result = []
    for i, (code, name, kana, grp, tax, role) in enumerate(STANDARD_ACCOUNTS):
        if entity_type == "sole" and role in ("retained",) or (entity_type == "sole" and code in ("400", "401", "410", "411")):
            continue
        if entity_type == "corp" and role in ("owner_capital", "owner_drawing", "owner_contrib"):
            continue
        result.append({
            "code": code,
            "name": name,
            "kana": kana,
            "category": GROUP_MAP[grp],
            "grp": grp,
            "default_tax_class": tax,
            "role": role,
            "sort_order": i * 10,
        })
    return result
