def resolve_role(value: str) -> str | None:
    """CSV 取込用: 役割をコードまたは日本語名から引く。"""
    v = (value or "").strip()
    if v in ("", "(なし)", "なし", "-"):
        return ""
    if v in ROLE_CODES:
        return v
    for r in ROLES:
        if v == r["name"]:
            return r["code"]
    return None


def resolve_bool(value: str, default: bool = True) -> bool:
    v = (value or "").strip().lower()
    if v == "":
        return default
    return v not in ("0", "false", "no", "n", "×", "x", "無効", "off")


def is_taxable(code: str) -> bool:
    t = tax_class(code)
    return t["kind"] in ("sales", "purchase") and t["rate"] > 0


def calc_tax_inclusive(amount: int, rate: int) -> int:
    """税込金額から内税額を計算(切捨て)。"""
    if rate <= 0 or amount == 0:
        return 0
    sign = 1 if amount >= 0 else -1
    return sign * (abs(amount) * rate // (100 + rate))


